package com.cortes.combat.weaponpack;

import com.cortes.combat.item.AutoProfile;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * El texto de un {@code auto-<modid>.yaml}, <b>sin un solo tipo de Minecraft</b>.
 *
 * <p><b>Clase separada de {@code AutoPackGenerator} por una razon medida, no por gusto:</b> el
 * generador importa {@code Item}, {@code ItemStack}, {@code BuiltInRegistries} e
 * {@code ItemTags}, asi que la JVM que corre los tests no puede cargarlo
 * ({@code NoClassDefFoundError} desde la primera linea del test). La verificacion de bytecode
 * resuelve los tipos de los cuerpos y no hay forma de pedirle que no -- asi que el cuerpo puro
 * vive aca y el adaptador al juego se queda con el escaneo.</p>
 *
 * <p>Las reglas del formato, y cada una tiene su razon en la ronda que lo escribio:</p>
 *
 * <ol>
 *   <li><b>Secciones por arquetipo, ids alfabeticos adentro</b> -- el archivo se lee de arriba
 *       abajo cuando alguien lo corrige, y una lista barajada por orden de registro se lee una
 *       vez y no se toca mas.</li>
 *   <li><b>El tier va como comentario</b>, no como numero: el dano del arma ajena ya escala
 *       por material en su propio mod, y la carga escala en el codigo
 *       ({@code AutoProfile.tieredCharge*}). Lo que el comentario da es la respuesta a
 *       "cual linea toco" sin mentir sobre el mecanismo.</li>
 *   <li><b>La espada larga es la unica con {@code reach}</b> -- es consenso de escritorio, no
 *       un dato del juego, y vive en el archivo para que el usuario lo pueda cambiar. (⌒‿⌒)</li>
 * </ol>
 */
public final class AutoPackYaml {

    private AutoPackYaml() {
    }

    /**
     * Version del formato y de las reglas de deteccion.
     *
     * <p><b>Existe para que una instalacion vieja reciba las reglas nuevas.</b> El generador
     * nunca pisa un archivo que existe -- es del usuario --, asi que sin un marcador de version
     * las armas que el clasificador aprendio a detectar despues (los tags comunes, las lanzas,
     * las dagas ajenas) se quedaban sin linea para siempre en todas las partidas ya creadas. Ese
     * es literalmente el reporte "solo la mitad de Simply Swords tiene stats": metadatos viejos
     * con un clasificador nuevo. (μ_μ)</p>
     */
    public static final int GENERATOR_VERSION = 2;

    /** El prefijo de los archivos que escribe este mod, y que no cuentan como cobertura. */
    public static final String AUTO_PREFIX = "auto-";

    /** Una arma ajena detectada, lista para el YAML. */
    public record Detected(String id, String archetype, Float longReach, AutoProfile.OreTier tier) {
    }

    /** El orden de las secciones: el mismo de la portada de arquetipos. */
    private static final List<String> ORDER = List.of("dagger", "sword", "rapier", "sabre",
            "spear", "polearm", "hammer", "mace", "axe");

    /** El titulo de la seccion, en uso: el nombre del arquetipo y el espanol al lado. */
    private static final Map<String, String> SPANISH = Map.of(
            "dagger", "dagas",
            "sword", "espadas",
            "rapier", "roperas",
            "sabre", "sables",
            "hammer", "martillos",
            "mace", "mazas",
            "spear", "lanzas",
            "polearm", "alabardas",
            "axe", "hachas");

    /**
     * El texto del YAML, ordenado: secciones por arquetipo (en el orden de la portada), ids
     * alfabeticos adentro, el tier anotado en cada linea.
     */
    public static String of(String modid, List<Detected> weapons) {
        List<Detected> sorted = new ArrayList<>(weapons);
        sorted.sort(Comparator
                .comparing((Detected d) -> order(d.archetype()))
                .thenComparing(Detected::id));

        StringBuilder out = new StringBuilder();
        out.append("# ================================================================\n");
        out.append("#  AUTOGENERADO POR CORTES COMBAT  /  AUTO-GENERATED BY CORTES COMBAT\n");
        out.append("#  mod: ").append(modid).append("\n");
        out.append("#  generator: ").append(GENERATOR_VERSION).append("\n");
        out.append("# ================================================================\n");
        out.append("#  ESTE ARCHIVO ES TUYO / THIS FILE IS YOURS:\n");
        out.append("#   - Cada linea se corrige o se borra aca; despues /cc reload.\n");
        out.append("#   - Borrar el archivo entero lo regenera en el proximo arranque\n");
        out.append("#     (Each line is fixed or deleted here, then /cc reload. Deleting\n");
        out.append("#     the whole file regenerates it on the next start.)\n");
        out.append("#   - Si el mod actualiza sus reglas, el archivo VIEJO se guarda como\n");
        out.append("#     <archivo>.bak y se escribe uno nuevo: tus ediciones quedan ahi.\n");
        out.append("#     (When this mod updates its rules, the OLD file is kept as\n");
        out.append("#     <file>.bak and a new one is written: your edits live there.)\n");
        out.append("#  REGLAS / RULES:\n");
        out.append("#   - dano y velocidad NO se declaran: el arma ya trae los suyos por\n");
        out.append("#     material, del mod que la hizo (damage and attack speed are NOT\n");
        out.append("#     declared: the item already carries its own per-material numbers)\n");
        out.append("#   - el tier anotado escala la CARGA en el codigo: mejor material =\n");
        out.append("#     carga completa antes y con mas bonus (the tier scales CHARGE in\n");
        out.append("#     code: better material = faster full charge and a bigger bonus)\n");
        out.append("#   - arquetipo equivocado: cambia el NOMBRE aca mismo (wrong archetype:\n");
        out.append("#     change the archetype NAME right here)\n");
        out.append("#   - spear usa el sistema del tridente (spear rides the trident system)\n");
        out.append("# ================================================================\n\n");
        out.append("version: 1\n\nweapons:\n");

        String current = null;
        for (Detected d : sorted) {
            if (!d.archetype().equals(current)) {
                current = d.archetype();
                out.append("\n  # ---- ").append(current);
                out.append(" (").append(SPANISH.getOrDefault(current, current));
                out.append(") ----\n");
            }
            out.append("  - match: { id: ").append(d.id()).append(" }   # tier: ");
            out.append(d.tier().name()).append('\n');
            out.append("    archetype: ").append(d.archetype()).append('\n');
            if (d.longReach() != null) {
                out.append("    reach: { distance: ").append(d.longReach()).append(" }\n");
            }
        }
        return out.toString();
    }

    private static int order(String archetype) {
        int index = ORDER.indexOf(archetype);
        return index < 0 ? Integer.MAX_VALUE : index;
    }

    /** El orden de las secciones, para el test que lo camina. */
    static List<String> order() {
        return ORDER;
    }

    /**
     * Si el archivo lo escribio la version actual del generador.
     *
     * <p><b>Vive aca y no en {@code AutoPackGenerator} por la razon de siempre</b>: el generador
     * importa tipos de Minecraft y esta JVM no puede cargarlo, asi que una regla que decide si
     * un archivo del usuario se reescribe o se respeta no puede vivir ahi -- quedaria sin test.
     * Esta version solo abre un archivo de texto. (⌒‿⌒)</p>
     *
     * <p>Se lee el encabezado y no el YAML entero: el marcador es una linea de comentario que el
     * loader ignora, y buscar el numero en el texto completo encontraria un {@code # tier:} con
     * el mismo digito.</p>
     */
    public static boolean isCurrent(java.nio.file.Path file) {
        try (var lines = java.nio.file.Files.lines(file, java.nio.charset.StandardCharsets.UTF_8)) {
            return lines.limit(12)
                    .filter(line -> line.startsWith("#  generator:"))
                    .map(line -> line.substring("#  generator:".length()).trim())
                    .mapToInt(Integer::parseInt)
                    .anyMatch(version -> version >= GENERATOR_VERSION);
        } catch (Exception unreadable) {
            // Un archivo que no se puede leer no puede probar que es actual: se respalda.
            return false;
        }
    }

    /**
     * Si un pack lo escribió este mod y no una persona.
     *
     * <p><b>El generador necesita esta pregunta para no abstenerse de su propia salida.</b> La
     * regla "un item ya contestado no genera línea" es correcta para los packs del usuario y
     * catastrófica para los {@code auto-*.yaml}: al regenerar, el store todavía tiene la versión
     * vieja cargada y todos los items aparecen contestados -- medido, un pack de ~170 entradas
     * quedó en 1. (μ_μ)</p>
     */
    public static boolean isAutoGenerated(String origin) {
        return origin != null && origin.toLowerCase().startsWith(AUTO_PREFIX);
    }
}
